"""BulkTranscriptomicsAdapter — bulk RNA-seq / microarray / time-series adapter.

Covers generic bulk-RNA-seq, microarray and time-series expression claims plus
study-level metadata (sequencing platform, alignment / normalisation / DE
tool). Single-cell-specific qualifiers (cell-type markers, cluster enrichment,
spatial localisation) live in ``SingleCellTranscriptomicsAdapter``.

The adapter is a pure-function claim enricher. It does not perform LLM
extraction, does not call out to external services, and does not write files.
Domain-specific data (gene name → CURIE lookups, ontology vocab subsets) is
shipped as bundled package resources, regenerated by maintainer scripts under
``data/build_*.py``.
"""
from __future__ import annotations

from collections.abc import Callable
from importlib.resources import files
from typing import Final

import rdflib

from indicium_adapters_transcriptomics._enrichment import CONCEPT_INDEX, GENE_INDEX
from indicium_adapters_transcriptomics._namespaces import TRANSCRIPTOMICS_PREFIXES
from indicium_adapters_transcriptomics._registries import accession_to_curie

__all__ = ["BulkTranscriptomicsAdapter", "accession_to_curie"]


# Slot names that may carry a gene / transcript / repository accession and
# therefore benefit from CURIE lookup. Kept narrow on purpose.
_ENRICHABLE_SLOTS: Final[tuple[str, ...]] = ("subject", "object")


# Bare-id columns of GeneIndex rows that need a prefix at CURIE-rendering time.
# HGNC values are stored already in `HGNC:NNNN` CURIE form, so they short-circuit
# the prefix step. The rest are bare ids (`ENSG…`, `54361`, …) and get prefixed
# via this map. The prefix strings match the keys of TRANSCRIPTOMICS_PREFIXES.
_PRINCIPAL_CURIE_PREFIX: Final[tuple[tuple[str, str | None], ...]] = (
    ("hgnc", None),          # already a CURIE
    ("ensembl", "ENSEMBL"),
    ("ncbigene", "NCBIGene"),
)

# Xref columns surfaced under `xrefs[slot]`. Bare ids (no prefixing).
_XREF_COLUMNS: Final[tuple[str, ...]] = (
    "hgnc", "ensembl", "ncbigene", "nemve1", "nvertx", "uniprot",
)


# --- Resolver dispatch (v0.4.0) --------------------------------------------
#
# Each resolver inspects a slot value (a gene name / accession / tool name)
# and returns ``(curie, xrefs_dict) | None``. xrefs are written under
# ``claim["xrefs"][slot]`` when non-empty; the resolver may return an empty
# dict when it has no xrefs to surface (accessions, for example).


def _resolve_accession(name: str) -> tuple[str, dict[str, str]] | None:
    curie = accession_to_curie(name)
    if curie is None:
        return None
    return curie, {}


def _resolve_gene(name: str) -> tuple[str, dict[str, str]] | None:
    row = GENE_INDEX.lookup(name)
    if row is None:
        return None
    # Principal CURIE: HGNC > Ensembl > NCBIGene. HGNC values are stored
    # already in CURIE form; the rest get prefixed here.
    curie: str | None = None
    for col, prefix in _PRINCIPAL_CURIE_PREFIX:
        val = row.get(col)
        if val:
            curie = val if prefix is None else f"{prefix}:{val}"
            break
    if curie is None:
        return None
    xrefs = {col: row[col] for col in _XREF_COLUMNS if row.get(col)}
    return curie, xrefs


def _resolve_concept(name: str) -> tuple[str, dict[str, str]] | None:
    row = CONCEPT_INDEX.lookup(name)
    if row is None:
        return None
    xref = {
        "curie": row["curie"],
        "label": row["label"],
        "ontology": row["ontology"],
    }
    if row.get("description"):
        xref["description"] = row["description"]
    return row["curie"], xref


_RESOLVERS: Final[dict[str, Callable[[str], tuple[str, dict[str, str]] | None]]] = {
    "accession": _resolve_accession,
    "gene":      _resolve_gene,
    "concept":   _resolve_concept,
}


# Default resolver priority — claim-level (feature) qualifiers fall here.
# Subject is usually a gene mention, so gene-lookup wins over the broader
# concept index. accession runs first because repository accessions are
# unambiguous and shouldn't be redirected via gene-symbol collisions.
_DEFAULT_PRIORITY: Final[tuple[str, ...]] = ("accession", "gene", "concept")


# Study-level metadata qualifiers — object is typically a tool / platform /
# database mention. Concept (incl. bio.tools) runs first so e.g. ``STAR`` in
# ``aligned_with: <study> STAR`` resolves to ``biotools:star`` (the aligner)
# rather than ``HGNC:11359`` (the steroidogenic acute regulatory protein
# gene). Accession still runs early so ``GSE168938`` in any slot stays a
# GEO CURIE; gene falls last so the fallback path still surfaces a gene
# CURIE when the corpus mention isn't a known tool.
_STUDY_LEVEL_PRIORITY: Final[tuple[str, ...]] = ("concept", "accession", "gene")


_QUALIFIER_PRIORITY: Final[dict[str, tuple[str, ...]]] = {
    # Study-level qualifiers — object slot typically carries a method /
    # platform / tool mention.
    "sequenced_on":     _STUDY_LEVEL_PRIORITY,
    "aligned_with":     _STUDY_LEVEL_PRIORITY,
    "quantified_with":  _STUDY_LEVEL_PRIORITY,
    "normalized_with":  _STUDY_LEVEL_PRIORITY,
    "tested_with":      _STUDY_LEVEL_PRIORITY,
    "uses_database":    _STUDY_LEVEL_PRIORITY,
    # consolidates_dataset stays on the default order — its object is a
    # repository accession, which the accession resolver handles first
    # under both priority maps anyway.
}


class BulkTranscriptomicsAdapter:
    """Bulk transcriptomics DomainAdapter (api_version=1).

    Qualifiers cover both claim-level assertions about genes / transcripts and
    study-level assay-metadata assertions for bulk RNA-seq, microarray and
    time-series experiments. Single-cell qualifiers live in
    ``SingleCellTranscriptomicsAdapter`` to keep the sets disjoint.

    Enrichment in v0.1.0 is limited to repository-accession CURIEs (GEO / SRA
    / ENA / ArrayExpress / ENCODE / BioProject / dbGaP / BioStudies).
    Gene-symbol enrichment (HGNC + Nemve1) arrives in v0.1.1; full vocabulary
    subsets in v0.2.0.
    """

    domain_id = "bulk-transcriptomics"
    api_version = 1

    qualifiers: frozenset[str] = frozenset({
        # Claim-level assertions about features (genes / transcripts / sets)
        "differentially_expressed_in",
        "co_expressed_with",
        "enriched_for",
        "expressed_in",
        "marker_of",
        "regulated_by",
        # Study-level assay-metadata qualifiers. Subject is typically a study
        # or capsule identifier; object is the platform / tool / database
        # literal — mirrors the v0.4 metabolomics pattern.
        "sequenced_on",
        "aligned_with",
        "quantified_with",
        "normalized_with",
        "tested_with",
        "uses_database",
        "consolidates_dataset",
    })

    ontology_prefixes: dict[str, str] = TRANSCRIPTOMICS_PREFIXES

    def extraction_context(self) -> str:
        return (
            "Domain: bulk transcriptomics. Extra qualifiers available: "
            "differentially_expressed_in, co_expressed_with, enriched_for, "
            "expressed_in, marker_of, regulated_by, sequenced_on, "
            "aligned_with, quantified_with, normalized_with, tested_with, "
            "uses_database, consolidates_dataset. "
            "Use canonical gene symbols (HGNC for human, MGI for mouse, "
            "official model-organism database symbols otherwise) for gene "
            "subjects and objects where possible. Study-level qualifiers "
            "(sequenced_on, aligned_with, quantified_with, normalized_with, "
            "tested_with, uses_database, consolidates_dataset) take a "
            "study / capsule / paper id as subject and a platform / tool / "
            "database / accession literal as object (e.g. 'Illumina HiSeq "
            "2500', 'STAR', 'HTSeq', 'TMM', 'DESeq2', 'Ensembl', "
            "'GEO:GSE168938'). Single-cell-specific claims (cell-type "
            "markers, cluster enrichment) belong in the single-cell adapter."
        )

    def enrich_claim(self, claim: dict) -> dict:
        """Enrich a claim with transcriptomics CURIEs (qualifier-aware).

        For each slot (subject, object), the resolver chain is selected by
        the claim's ``qualifier``:

        - **Study-level qualifiers** (``sequenced_on``, ``aligned_with``,
          ``quantified_with``, ``normalized_with``, ``tested_with``,
          ``uses_database``) use ``concept`` → ``accession`` → ``gene``,
          so a tool name like ``STAR`` resolves to ``biotools:star``
          rather than ``HGNC:11359`` (the steroidogenic acute regulatory
          protein gene with the same symbol).
        - **All other qualifiers** (claim-level feature assertions, and
          ``consolidates_dataset``) use the default ``accession`` →
          ``gene`` → ``concept`` order — gene-symbol mentions are
          dominant in feature claims, so gene lookup wins.

        The first resolver that returns a hit wins; later resolvers are
        not consulted for that slot. ``ontology_terms[slot]`` carries the
        principal CURIE; ``xrefs[slot]`` carries the resolver-specific
        cross-references (HGNC/Ensembl/NCBIGene/Nemve1/NvERTx/UniProt
        for genes; ``{curie, label, ontology, description}`` for
        concepts; nothing for accessions).

        Pure function — never mutates the input dict.
        """
        claim = dict(claim)
        if "ontology_terms" in claim:
            claim["ontology_terms"] = dict(claim["ontology_terms"])
        if "xrefs" in claim:
            claim["xrefs"] = dict(claim["xrefs"])

        qualifier = (claim.get("qualifier") or "").strip()
        priority = _QUALIFIER_PRIORITY.get(qualifier, _DEFAULT_PRIORITY)

        for slot in _ENRICHABLE_SLOTS:
            name = (claim.get(slot) or "").strip()
            if not name:
                continue
            for resolver_name in priority:
                resolver = _RESOLVERS[resolver_name]
                result = resolver(name)
                if result is None:
                    continue
                curie, xrefs = result
                claim.setdefault("ontology_terms", {})[slot] = curie
                if xrefs:
                    claim.setdefault("xrefs", {})[slot] = xrefs
                break  # first hit per slot wins

        return claim

    def shacl_shapes(self) -> rdflib.Graph:
        """Return ASB-claim SHACL shapes (CURIE format validation only).

        Pipeline-level RDF validation for transcriptomics workflows (e.g. SO /
        UBERON / CL class shapes) lives upstream in the consuming graph store,
        not here.
        """
        g = rdflib.Graph()
        ttl = files("indicium_adapters_transcriptomics.shapes").joinpath(
            "transcriptomics.shapes.ttl"
        )
        g.parse(ttl.open("rb"), format="turtle")
        return g
