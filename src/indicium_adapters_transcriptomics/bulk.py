"""BulkTranscriptomicsAdapter — bulk RNA-seq / microarray / time-series adapter.

Covers generic bulk-RNA-seq, microarray and time-series expression claims plus
study-level metadata (sequencing platform, alignment / normalisation / DE
tool). Single-cell-specific qualifiers (cell-type markers, cluster enrichment,
spatial localisation) live in ``SingleCellTranscriptomicsAdapter``.

The adapter is a pure-function claim enricher. It does not perform LLM
extraction, does not call out to external services, and does not write files.
Domain-specific data (gene name → CURIE lookups, ontology vocab subsets) is
shipped as bundled package resources, regenerated by maintainer scripts under
``data/build_*.py``.
"""
from __future__ import annotations

from importlib.resources import files
from typing import Final

import rdflib

from indicium_adapters_transcriptomics._enrichment import GENE_INDEX
from indicium_adapters_transcriptomics._namespaces import TRANSCRIPTOMICS_PREFIXES
from indicium_adapters_transcriptomics._registries import accession_to_curie

__all__ = ["BulkTranscriptomicsAdapter", "accession_to_curie"]


# Slot names that may carry a gene / transcript / repository accession and
# therefore benefit from CURIE lookup. Kept narrow on purpose.
_ENRICHABLE_SLOTS: Final[tuple[str, ...]] = ("subject", "object")


class BulkTranscriptomicsAdapter:
    """Bulk transcriptomics DomainAdapter (api_version=1).

    Qualifiers cover both claim-level assertions about genes / transcripts and
    study-level assay-metadata assertions for bulk RNA-seq, microarray and
    time-series experiments. Single-cell qualifiers live in
    ``SingleCellTranscriptomicsAdapter`` to keep the sets disjoint.

    Enrichment in v0.1.0 is limited to repository-accession CURIEs (GEO / SRA
    / ENA / ArrayExpress / ENCODE / BioProject / dbGaP / BioStudies).
    Gene-symbol enrichment (HGNC + Nemve1) arrives in v0.1.1; full vocabulary
    subsets in v0.2.0.
    """

    domain_id = "bulk-transcriptomics"
    api_version = 1

    qualifiers: frozenset[str] = frozenset({
        # Claim-level assertions about features (genes / transcripts / sets)
        "differentially_expressed_in",
        "co_expressed_with",
        "enriched_for",
        "expressed_in",
        "marker_of",
        "regulated_by",
        # Study-level assay-metadata qualifiers. Subject is typically a study
        # or capsule identifier; object is the platform / tool / database
        # literal — mirrors the v0.4 metabolomics pattern.
        "sequenced_on",
        "aligned_with",
        "quantified_with",
        "normalized_with",
        "tested_with",
        "uses_database",
        "consolidates_dataset",
    })

    ontology_prefixes: dict[str, str] = TRANSCRIPTOMICS_PREFIXES

    def extraction_context(self) -> str:
        return (
            "Domain: bulk transcriptomics. Extra qualifiers available: "
            "differentially_expressed_in, co_expressed_with, enriched_for, "
            "expressed_in, marker_of, regulated_by, sequenced_on, "
            "aligned_with, quantified_with, normalized_with, tested_with, "
            "uses_database, consolidates_dataset. "
            "Use canonical gene symbols (HGNC for human, MGI for mouse, "
            "official model-organism database symbols otherwise) for gene "
            "subjects and objects where possible. Study-level qualifiers "
            "(sequenced_on, aligned_with, quantified_with, normalized_with, "
            "tested_with, uses_database, consolidates_dataset) take a "
            "study / capsule / paper id as subject and a platform / tool / "
            "database / accession literal as object (e.g. 'Illumina HiSeq "
            "2500', 'STAR', 'HTSeq', 'TMM', 'DESeq2', 'Ensembl', "
            "'GEO:GSE168938'). Single-cell-specific claims (cell-type "
            "markers, cluster enrichment) belong in the single-cell adapter."
        )

    def enrich_claim(self, claim: dict) -> dict:
        """Enrich a claim with transcriptomics CURIEs.

        v0.1.0 behaviour: recognise repository accessions in `subject` /
        `object` and add them to ``ontology_terms``. Gene-symbol lookup (HGNC
        + Nemve1) is wired up in v0.1.1.

        Pure function — never mutates the input dict.
        """
        claim = dict(claim)
        if "ontology_terms" in claim:
            claim["ontology_terms"] = dict(claim["ontology_terms"])
        if "xrefs" in claim:
            claim["xrefs"] = dict(claim["xrefs"])

        for slot in _ENRICHABLE_SLOTS:
            name = (claim.get(slot) or "").strip()
            if not name:
                continue
            # Accession lookup first — repository accessions resolve
            # deterministically and outrank any gene-name match.
            if curie := accession_to_curie(name):
                claim.setdefault("ontology_terms", {})[slot] = curie
                continue
            # Gene-name lookup (placeholder in v0.1.0; real index from v0.1.1).
            if row := GENE_INDEX.lookup(name):
                for col in ("hgnc", "ensembl", "ncbigene"):
                    if curie := row.get(col):
                        claim.setdefault("ontology_terms", {})[slot] = curie
                        break

        return claim

    def shacl_shapes(self) -> rdflib.Graph:
        """Return ASB-claim SHACL shapes (CURIE format validation only).

        Pipeline-level RDF validation for transcriptomics workflows (e.g. SO /
        UBERON / CL class shapes) lives upstream in the consuming graph store,
        not here.
        """
        g = rdflib.Graph()
        ttl = files("indicium_adapters_transcriptomics.shapes").joinpath(
            "transcriptomics.shapes.ttl"
        )
        g.parse(ttl.open("rb"), format="turtle")
        return g
